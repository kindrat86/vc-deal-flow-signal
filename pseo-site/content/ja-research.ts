export function getJaFindingBySlug(slug: string): JaFinding | undefined {
  return JA_FINDINGS.find((f) => f.slug === slug);
}

export function getAllJaFindingSlugs(): string[] {
  return JA_FINDINGS.map((f) => f.slug);
}
