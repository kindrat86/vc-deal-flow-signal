#!/usr/bin/env node
/**
 * gen-critical-css.mjs - Deterministic critical-CSS extractor (FCP fix 2026-08-16).
 *
 * public/ux.css (the R16/R18 portfolio design system) is ~33KB and loaded on
 * every page as a render-blocking <link>. Only a subset of it is load-bearing
 * on THIS Next.js app: the unlayered base-element sections (tokens, reset,
 * typography, headings, links, touch targets, safe-area, focus, images, forms,
 * spacing, print, mobile breakpoints, dark palette, reduced motion). Every
 * .ux-* COMPONENT class (cards, badges, skeletons, sheets, carousels, toasts,
 * fab, grid, offline bar, etc.) is unused here (verified 2026-08-16: zero
 * matches across app/, components/, embed/, widgets/).
 *
 * Strategy: bundle the load-bearing sections into the existing render-blocking
 * Next CSS chunk via `import "./critical.css"` in the root layout, and load the
 * FULL /ux.css asynchronously (media="print" + load-swap) so it no longer
 * blocks first paint. First paint renders identically (critical rules are
 * verbatim copies), and the async file adds zero visual change when it lands.
 *
 * Usage:
 *   node scripts/gen-critical-css.mjs            # (re)generate app/critical.css
 *   node scripts/gen-critical-css.mjs --check    # exit 1 if app/critical.css is stale
 *
 * Sections are keyed by their numbered comment markers ("/* --- N. NAME ...")
 * so the extractor survives edits to ux.css without line-number brittleness.
 * A source-hash header in the generated file lets verify-no-regressions.ts
 * fail the build when public/ux.css changes without regeneration.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

const ROOT = process.cwd();
const SRC = join(ROOT, "public", "ux.css");
const OUT = join(ROOT, "app", "critical.css");

/** Numbered section markers: `/* --- 12. NAME ---... *\/` */
const SECTION_RE = /^\/\*\s+─{2}\s+(\d+)\.\s/;

// Sections of public/ux.css that are load-bearing on this app.
// Whole-section copies keep the cascade verbatim (zero visual drift).
const KEEP = new Set([0, 1, 2, 3, 4, 5, 14, 15, 17, 18, 19, 40, 41, 42, 43]);

function buildCritical(src) {
  const lines = src.split("\n");
  const out = [];
  let current = null;
  for (const line of lines) {
    const m = line.match(SECTION_RE);
    if (m) {
      current = parseInt(m[1], 10);
    }
    if (current !== null && KEEP.has(current)) {
      out.push(line);
    }
  }
  // Drop the trailing newline-only line and normalize a single trailing \n.
  let body = out.join("\n").replace(/\n+$/, "") + "\n";
  const hash = createHash("sha1").update(src).digest("hex").slice(0, 16);
  const header =
    "/* AUTO-GENERATED by scripts/gen-critical-css.mjs, do not edit by hand.\n" +
    "   Critical (load-bearing) subset of public/ux.css for first paint.\n" +
    `   source-sha1: ${hash}\n` +
    "   Regenerate: node scripts/gen-critical-css.mjs */\n";
  return header + body;
}

const src = readFileSync(SRC, "utf8");
const generated = buildCritical(src);

if (process.argv.includes("--check")) {
  if (!existsSync(OUT)) {
    console.error("app/critical.css missing, run: node scripts/gen-critical-css.mjs");
    process.exit(1);
  }
  const current = readFileSync(OUT, "utf8");
  if (current !== generated) {
    console.error(
      "app/critical.css is STALE (public/ux.css changed without regeneration).\n" +
        "Run: node scripts/gen-critical-css.mjs"
    );
    process.exit(1);
  }
  console.log("critical.css is fresh");
  process.exit(0);
}

writeFileSync(OUT, generated);
console.log(`wrote ${OUT} (${generated.length} bytes, source sha1 ${generated.match(/source-sha1: (\w+)/)[1]})`);
