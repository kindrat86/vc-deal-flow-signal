#!/usr/bin/env node
// Writes lib/sector-count.ts from data/startups.json so every surface that
// states a sector count reads it from the data, never a hard-coded number
// (2026-11-03 honesty pass: the site said "15 sectors" while the data had 20).
// Runs in prebuild (before and after the data fetch) and is idempotent.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const data = JSON.parse(readFileSync(join(root, "data/startups.json"), "utf8"));
const period = data.periods.find((p) => p.current) ?? data.periods[0];
const active = data.sectors.filter((s) => {
  const snap = s.periods?.[period.slug];
  return snap && Array.isArray(snap.startups) && snap.startups.length > 0;
});
const out = `// Generated by scripts/write-sector-count.mjs from data/startups.json. Do not edit.
// Client-safe: a plain constant, no data import.
/** Sectors with startups in the current period (${period.slug}). */
export const SECTOR_COUNT = ${active.length};
/** Current period slug the count was taken from. */
export const SECTOR_COUNT_PERIOD = ${JSON.stringify(period.slug)};
`;
const path = join(root, "lib/sector-count.ts");
let prev = "";
try { prev = readFileSync(path, "utf8"); } catch {}
if (prev !== out) writeFileSync(path, out);
console.log(`sector-count: ${active.length} active sectors in ${period.slug}`);
