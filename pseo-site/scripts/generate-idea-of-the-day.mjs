/**
 * Idea of the Day, generator.
 *
 * Backfills (or appends) one ideation page per calendar day, drawn from the
 * existing q2-2026 startups dataset. Each page reframes a tracked repo as
 * "the SaaS opportunity hiding in this signal", same data, builder-side lens.
 *
 * Modes:
 *   --backfill <N>          Mint N days of seed entries ending at --through.
 *   --through YYYY-MM-DD    Anchor date (default = today, UTC).
 *   --append                Append exactly one entry for --through (cron mode).
 *   --out PATH              Output JSON path (default = data/ideas-of-the-day.json).
 *
 * Output schema is the single source of truth for the
 * /idea-of-the-day route family. See lib/ideas-of-the-day.ts for types.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");

const args = parseArgs(process.argv.slice(2));
const PERIOD = "q2-2026";
const OUT_PATH = args.out
  ? path.resolve(process.cwd(), args.out)
  : path.join(REPO_ROOT, "data", "ideas-of-the-day.json");

const startups = JSON.parse(
  readFileSync(path.join(REPO_ROOT, "data", "startups.json"), "utf8"),
);

const existing = existsSync(OUT_PATH)
  ? JSON.parse(readFileSync(OUT_PATH, "utf8"))
  : { _doc: docstring(), entries: [] };

const usedRepoNames = new Set(existing.entries.map((e) => e.repo.name));

// ---------------------------------------------------------------------------
// Candidate pool
// ---------------------------------------------------------------------------
const pool = collectPool();
if (pool.length === 0) {
  console.error("[idea-of-the-day] empty candidate pool, abort.");
  process.exit(1);
}

// ---------------------------------------------------------------------------
// Mode dispatch, wrapped in main() so const lookup tables below are
// initialised before the first call to buildEntry().
// ---------------------------------------------------------------------------
function main() {
  const today = args.through ?? new Date().toISOString().slice(0, 10);

  if (args.append) {
    if (existing.entries.find((e) => e.date === today)) {
      console.log(`[idea-of-the-day] ${today} already exists, skipping.`);
      return;
    }
    const next = pickFor(today, pool, usedRepoNames);
    existing.entries.push(next);
    existing.entries.sort((a, b) =>
      a.date < b.date ? -1 : a.date > b.date ? 1 : 0,
    );
    writeFileSync(OUT_PATH, JSON.stringify(existing, null, 2) + "\n");
    console.log(`[idea-of-the-day] appended ${today} → ${next.repo.name}`);
    return;
  }

  const n = Number(args.backfill ?? 30);
  const dates = [];
  for (let i = n - 1; i >= 0; i--) {
    dates.push(addDays(today, -i));
  }

  const out = { _doc: docstring(), entries: existing.entries.slice() };
  const outDates = new Set(out.entries.map((e) => e.date));

  for (const date of dates) {
    if (outDates.has(date)) continue;
    const entry = pickFor(date, pool, usedRepoNames);
    out.entries.push(entry);
    outDates.add(date);
  }
  out.entries.sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : 0));

  writeFileSync(OUT_PATH, JSON.stringify(out, null, 2) + "\n");
  console.log(
    `[idea-of-the-day] wrote ${out.entries.length} entries → ${OUT_PATH}`,
  );
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------
function parseArgs(argv) {
  const o = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--backfill") o.backfill = argv[++i];
    else if (a === "--through") o.through = argv[++i];
    else if (a === "--append") o.append = true;
    else if (a === "--out") o.out = argv[++i];
  }
  return o;
}

function addDays(iso, n) {
  const d = new Date(iso + "T00:00:00Z");
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
}

function parsePct(s) {
  if (!s) return 0;
  const m = String(s).match(/-?\d+/);
  if (!m) return 0;
  const n = parseInt(m[0], 10);
  // Demote suspected bot-inflation (>500% on a 14d window is rare and noisy)
  if (n > 500) return -1;
  return n;
}

function docstring() {
  return [
    "Idea of the Day, one ideation page per calendar day.",
    "Each entry reframes a tracked repo as 'the SaaS opportunity hiding in this signal'.",
    "Generated by scripts/generate-idea-of-the-day.mjs. Append mode runs daily via cron.",
    "Schema is the source of truth for /idea-of-the-day routes; see lib/ideas-of-the-day.ts.",
  ].join(" ");
}

function collectPool() {
  const all = [];
  for (const s of startups.sectors) {
    const p = s.periods[PERIOD];
    if (!p) continue;
    for (const st of p.startups) {
      all.push({
        name: st.name,
        description: st.description || "",
        stage: st.stage,
        geography: st.geography,
        sector: s.name,
        sectorSlug: s.slug,
        signalType: st.signalType,
        commitVelocity14d: st.commitVelocity14d ?? 0,
        commitVelocityChange: st.commitVelocityChange ?? "+0%",
        contributors: st.contributors ?? 0,
        contributorGrowth: st.contributorGrowth ?? "+0%",
        newRepos: st.newRepos ?? 0,
        githubUrl: st.githubUrl,
      });
    }
  }

  all.sort((a, b) => {
    const da = parsePct(a.commitVelocityChange);
    const db = parsePct(b.commitVelocityChange);
    if (da !== db) return db - da;
    return (b.contributors || 0) - (a.contributors || 0);
  });

  // Diversify: round-robin by sector so a 30-day backfill rotates topics.
  const bySector = {};
  for (const x of all) {
    (bySector[x.sectorSlug] = bySector[x.sectorSlug] || []).push(x);
  }
  const sectorOrder = Object.keys(bySector);
  const rotated = [];
  let idx = 0;
  while (sectorOrder.some((s) => bySector[s].length > 0)) {
    const s = sectorOrder[idx % sectorOrder.length];
    if (bySector[s].length > 0) rotated.push(bySector[s].shift());
    idx++;
  }
  return rotated;
}

function pickFor(date, pool, usedNames) {
  // Deterministic per-date selection: hash the date into the pool so a
  // re-run produces a stable mapping. Skip names already used in the file.
  const seed = hashDate(date);
  let cursor = seed % pool.length;
  let tries = 0;
  while (tries < pool.length) {
    const cand = pool[cursor];
    if (!usedNames.has(cand.name)) {
      usedNames.add(cand.name);
      return buildEntry(date, cand);
    }
    cursor = (cursor + 1) % pool.length;
    tries++;
  }
  // Pool exhausted, fall through to allow repeats (year 2+).
  const cand = pool[seed % pool.length];
  return buildEntry(date, cand);
}

function hashDate(iso) {
  let h = 2166136261;
  for (let i = 0; i < iso.length; i++) {
    h ^= iso.charCodeAt(i);
    h = (h * 16777619) >>> 0;
  }
  return h;
}

function buildEntry(date, repo) {
  const headline = makeHeadline(repo);
  const hook = makeHook(repo);
  const ideaThesis = makeThesis(repo);
  const buildAngles = makeAngles(repo);
  const distributionPlay = makeDistribution(repo);
  const signalReading = makeSignalReading(repo);

  return {
    date,
    slug: date,
    headline,
    hook,
    repo: {
      name: repo.name,
      githubUrl: repo.githubUrl,
      stage: repo.stage,
      geography: repo.geography,
      sector: repo.sector,
      sectorSlug: repo.sectorSlug,
      signalType: repo.signalType,
      commitVelocity14d: repo.commitVelocity14d,
      commitVelocityChange: repo.commitVelocityChange,
      contributors: repo.contributors,
      contributorGrowth: repo.contributorGrowth,
      newRepos: repo.newRepos,
      description: repo.description,
    },
    ideaThesis,
    buildAngles,
    distributionPlay,
    signalReading,
    publishedAt: `${date}T09:00:00Z`,
  };
}

// ---------------------------------------------------------------------------
// Copy templates, deterministic, signal-shape aware.
// Kept short on purpose: the page itself renders the rest of the framing.
// ---------------------------------------------------------------------------
function makeHeadline(r) {
  const pct = r.commitVelocityChange;
  const sector = r.sector;
  const signal = r.signalType.toLowerCase();
  if (pct.startsWith("+")) {
    return `The ${sector.toLowerCase()} opening hiding in a ${pct} ${signal}`;
  }
  if (pct.startsWith("-")) {
    return `The ${sector.toLowerCase()} reset hiding in a ${pct} ${signal}`;
  }
  return `The ${sector.toLowerCase()} idea hiding in a ${signal}`;
}

function makeHook(r) {
  const stage = r.stage;
  const sector = r.sector;
  const pct = r.commitVelocityChange;
  const v = r.commitVelocity14d;
  const sigShort = shortSignal(r.signalType);
  if (pct.startsWith("+")) {
    return `${capitalize(stage)} ${sector.toLowerCase()} teams shipping ${v.toLocaleString()} commits in 14 days at ${pct} aren't just building product, they're broadcasting the ${sigShort} that usually precedes a raise.`;
  }
  return `${capitalize(stage)} ${sector.toLowerCase()} teams cooling to ${v.toLocaleString()} commits over 14 days (${pct}) are showing the ${sigShort} pattern, a recoverable dip, not a flatline, and the natural moment to build the next adjacent tool.`;
}

function makeThesis(r) {
  const sector = r.sector;
  const signal = r.signalType;
  const stage = r.stage;
  const contrib = r.contributors;
  return [
    `${sector} has a buyer who is also a builder. The category incumbents shipped for an ops/HR/finance lead;`,
    `the next wave ships for the engineer running that function. Read the repo: ${signal.toLowerCase()},`,
    `${stage.toLowerCase()} team, ${contrib} contributors. That's the shape of a team that crosses the next funding line`,
    `on engineering output, not enterprise sales, and the gap they leave is the wedge for an indie or two-founder`,
    `tool that does one job better than the suite they're inside of.`,
  ].join(" ");
}

function makeAngles(r) {
  // Templated by sector-family; falls through to generic if no match.
  const fam = sectorFamily(r.sectorSlug);
  const angles = ANGLE_TEMPLATES[fam] ?? ANGLE_TEMPLATES.default;
  // Replace {sector} token so the bullet reads natively.
  return angles.map((a) => a.replace(/\{sector\}/g, r.sector.toLowerCase()));
}

function makeDistribution(r) {
  const fam = sectorFamily(r.sectorSlug);
  const plays = DISTRIBUTION_PLAYS[fam] ?? DISTRIBUTION_PLAYS.default;
  return plays.replace(/\{sector\}/g, r.sector.toLowerCase());
}

function makeSignalReading(r) {
  const v = r.commitVelocity14d;
  const pct = r.commitVelocityChange;
  const c = r.contributors;
  const cg = r.contributorGrowth;
  const nr = r.newRepos;
  const items = [
    {
      metric: `${v.toLocaleString()} commits / 14 days`,
      reading:
        v >= 1000
          ? "Top-1% sustained shipping rate; a cadence usually correlated with imminent fundraise news in the 60-day window."
          : v >= 200
            ? "Healthy mid-stage build pace, above ambient noise, below frenzy. Read as steady-state hiring without a burst."
            : v >= 50
              ? "Maintenance-level cadence. The story isn't the volume; it's whatever else moved alongside it."
              : "Low absolute volume. The signal is the change-in-change, not the raw count, see the next metric.",
    },
    {
      metric: `${pct} commit-velocity change`,
      reading: pct.startsWith("+")
        ? "Trend is still accelerating, not peaking. A positive change-in-change is the leading edge of the curve, not the back of it."
        : pct === "+0%"
          ? "Flat. The interesting question is whether the contributor or new-repo lines moved while volume stayed put."
          : "Cooling. Often a deliberate slowdown for refactor, rebrand, or hiring, read alongside the next two lines before calling it a decline.",
    },
    {
      metric: `${c} contributors (${cg})`,
      reading:
        c <= 5
          ? "Founding-team-still-coding signal. Hiring will be the next-cycle move; ATS / sourcing tools are the natural wedge."
          : c <= 30
            ? "Small core team, likely seed-funded with focused velocity. The opportunity is adjacent tooling that augments the small team."
            : "Mature contributor base. The opportunity is less in displacing them and more in serving the engineers who depend on them.",
    },
  ];
  if (nr > 0) {
    items.push({
      metric: `${nr} new repos in window`,
      reading:
        "New repository creation is the classic platform-expansion signal, a team carving the next product surface out of the same codebase. The seam between the old repo and the new one is where a single-purpose external tool lives.",
    });
  }
  return items;
}

function sectorFamily(slug) {
  if (["ai-ml", "data-infrastructure", "developer-tools"].includes(slug)) return "ai-dev";
  if (["fintech", "web3"].includes(slug)) return "fintech";
  if (["climate-tech", "agtech", "supply-chain"].includes(slug)) return "physical";
  if (["healthcare", "biotech", "legal-tech"].includes(slug)) return "regulated";
  if (["hr-tech", "edtech", "enterprise-saas"].includes(slug)) return "people-ops";
  if (["gaming", "social-community", "creator-economy"].includes(slug)) return "consumer";
  if (["cybersecurity", "proptech", "e-commerce-infrastructure"].includes(slug)) return "vertical-saas";
  if (["robotics", "space-tech"].includes(slug)) return "deep-tech";
  return "default";
}

