function shortSignal(s) {
  const t = s.toLowerCase();
  if (t.includes("hiring")) return "hiring-burst";
  if (t.includes("deploy")) return "deploy-frequency";
  if (t.includes("framework")) return "framework-migration";
  if (t.includes("infra")) return "infra-buildout";
  if (t.includes("burst")) return "burst";
  return "acceleration";
}

function capitalize(s) {
  return s ? s[0].toUpperCase() + s.slice(1) : s;
}

